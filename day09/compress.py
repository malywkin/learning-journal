"""День 9 — управление контекстом: СЖАТИЕ истории диалога.

Два режима с ОДИНАКОВОЙ ручкой `build(system_prompt, history) -> messages`.
Агенту всё равно, какой режим ему дали (инкапсуляция — как с памятью в Дне 7):
он просто зовёт context.build() и шлёт результат в модель.

  NoCompression  — «без сжатия»: РОЛЬ + ВСЯ история как есть. Вход растёт
                   с каждым ходом (мы шлём накопленное заново) и рано или поздно
                   упирается в окно — это ровно боль Дня 8.

  RollingSummary — «со сжатием»: РОЛЬ + [КОПИЛКА-summary] + последние N реплик
                   ДОСЛОВНО. Старое (что выпало за окно) сворачивается в одну
                   накопительную копилку и подставляется ВМЕСТО полной истории.
                   Payload перестаёт расти лавиной — выходит «пила» у потолка.

Два рычага RollingSummary:
  keep_last — ОКНО в сообщениях: сколько свежих реплик слать ДОСЛОВНО
              (точность свежего разговора);
  trigger   — ПОТОЛОК: как несвёрнутых сообщений накопилось >= trigger,
              сворачиваем всё, кроме последних keep_last, в копилку.

Подводный камень (увидим живьём в demos.py): копилка НАКОПИТЕЛЬНАЯ — на каждом
срабатывании старую копилку + новый выпавший кусок сжимаем ЗАНОВО. Ошибки могут
накапливаться («дрейф» — как фотокопия с фотокопии). Главная защита — GUARDRAIL:
инструкция суммаризатору явно велит сохранять имена/числа/даты/договорённости.
"""

# Инструкция суммаризатору. ЭТО рычаг, которым мы влияем на содержимое копилки
# (а не «модель сама решает»): требуем держать конкретику — но СТРОГО из диалога.
# ВАЖНО (урок вживую): на слабой модели инструкция «обязательно сохрани имена/числа»
# при бедном контенте провоцирует ВЫДУМЫВАНИЕ — модель заполняет ожидание выдуманными
# сущностями. Поэтому явно ЗАПРЕЩАЕМ придумывать и велим быть короткой на пустом куске.
DEFAULT_GUARDRAIL = (
    "Ты делаешь фактологическую выжимку диалога для памяти ассистента. "
    "Опирайся ИСКЛЮЧИТЕЛЬНО на текст ниже: НИЧЕГО не придумывай — не добавляй имён, "
    "чисел, номеров, компаний, дат или деталей, которых в диалоге НЕТ. "
    "Сохрани те конкретные факты, что РЕАЛЬНО присутствуют (имена, числа, даты, "
    "договорённости, открытые вопросы). Если в куске мало содержания — сводка короткая "
    "(1–3 предложения), это нормально. Тебе дают ПРЕДЫДУЩУЮ сводку и НОВЫЙ кусок — верни "
    "ОДНУ обновлённую сводку, без вступлений и воды, только сводку."
)

# Намеренно ПЛОХАЯ инструкция — для демо «когда summary ВРЕДИТ»: просим общий
# пересказ, и конкретика (тот самый номер проекта) систематически вымывается.
NAIVE_GUARDRAIL = "Кратко, в одно предложение, перескажи, о чём в целом шёл разговор."


class NoCompression:
    """Базовый режим: РОЛЬ + ВСЯ история. Ничего не сжимаем (это и есть «до»)."""

    name = "без сжатия"

    def build(self, system_prompt, history):
        return [{"role": "system", "content": system_prompt}, *history]

    def view(self):
        """Состояние для «капота» (у этого режима копилки нет)."""
        return {"mode": self.name, "summary": "", "folded": 0, "events": []}


class RollingSummary:
    """Сжатие: РОЛЬ + [копилка] + последние keep_last реплик дословно.

    summarizer — функция (old_summary, chunk_messages, guardrail) -> (text, usage).
    Её даёт агент (отдельный вызов LLM). Так модуль сжатия не знает, КАК именно
    зовётся модель — он лишь решает, ЧТО и КОГДА сворачивать.
    """

    name = "со сжатием"

    def __init__(self, summarizer, keep_last=4, trigger=10, guardrail=DEFAULT_GUARDRAIL):
        self.summarizer = summarizer
        self.keep_last = keep_last        # ОКНО (в сообщениях): свежее — дословно
        self.trigger = trigger            # ПОТОЛОК: при стольких несвёрнутых — сворачиваем
        self.guardrail = guardrail
        self.summary = ""                 # КОПИЛКА (накопительная, перезаписывается)
        self.folded = 0                   # сколько РАННИХ сообщений уже свёрнуто в копилку
        self.events = []                  # лог срабатываний сжатия (для «капота»)
        self.summ_usage = []              # usage суммаризирующих вызовов = СВОЯ цена сжатия

    def maybe_compress(self, history):
        """Если несвёрнутых сообщений накопилось >= trigger — свернуть лишнее.

        Сворачиваем НЕ всё подряд, а только то, что вышло за окно: оставляем
        последние keep_last дословно, остальное несвёрнутое уходит суммаризатору.
        """
        unfolded = history[self.folded:]          # ещё не попавшее в копилку
        if len(unfolded) < self.trigger:
            return None                            # потолок не достигнут — рано
        chunk = unfolded[:-self.keep_last] if self.keep_last else list(unfolded)
        if not chunk:
            return None
        # старая копилка + новый выпавший кусок → ОДНА обновлённая копилка
        text, usage = self.summarizer(self.summary, chunk, self.guardrail)
        self.summary = (text or "").strip()
        self.folded += len(chunk)
        ev = {
            "at_history_len": len(history),
            "folded_now": len(chunk),
            "folded_total": self.folded,
            "summary_chars": len(self.summary),
        }
        self.events.append(ev)
        if usage is not None:
            self.summ_usage.append(usage)
        return ev

    def build(self, system_prompt, history):
        self.maybe_compress(history)
        recent = history[self.folded:]            # ОКНО: дословный хвост
        msgs = [{"role": "system", "content": system_prompt}]
        if self.summary:                          # КОПИЛКА (если уже есть что сворачивать)
            msgs.append({
                "role": "system",
                "content": "Сводка предыдущего разговора (контекст):\n" + self.summary,
            })
        msgs += recent
        return msgs

    def view(self):
        return {
            "mode": self.name,
            "summary": self.summary,
            "folded": self.folded,
            "keep_last": self.keep_last,
            "trigger": self.trigger,
            "events": self.events,
            "summarizations": len(self.events),
        }
