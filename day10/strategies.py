"""День 10 — управление контекстом БЕЗ суммаризации: три стратегии.

Тот же контракт, что в Дне 9: объект-стратегия с ручкой
    build(system_prompt, history) -> messages
и view() для «капота». Агент НЕ знает, какую стратегию ему дали — он просто
зовёт context.build() и шлёт результат в модель (инкапсуляция, как с памятью
в Дне 7 и со сжатием в Дне 9).

Три стратегии — три РАЗНЫХ ответа на вопрос «что делать со старым контекстом»,
и ни одна не использует summary (в этом весь смысл Дня 10):

  SlidingWindow — РОЛЬ + последние N сообщений. Остальное ОТРЕЗАЕМ и не шлём.
                  Самая дешёвая (НЕТ второго вызова LLM — чистая нарезка списка),
                  размер запроса постоянный → не переполнится. Но забывчивая:
                  что выпало за окно — потеряно навсегда (амнезия).

  StickyFacts   — РОЛЬ + КАРТОЧКА фактов (ключ→значение) + последние N сообщений.
                  Старый ТЕКСТ выкидываем (как окно), но перед этим важные поля
                  выписываем на карточку и носим её всегда. Карточку обновляет
                  ОТДЕЛЬНЫЙ вызов LLM после каждой реплики пользователя — это
                  миниатюра mem0.add(). Дороже окна на один вызов, но факт доживает.

  Branching     — ДРУГОЙ ЖАНР: не «что слать», а «сколько параллельных историй
                  держим». Общий неизменяемый СТВОЛ (до закладки) хранится ОДИН
                  раз; каждая ВЕТКА — только своя дельта после закладки. Операции
                  в одной ветке не могут задеть другую. Это про развилки сценариев,
                  а не про экономию токенов.

Чем карточка (StickyFacts) отличается от справки (RollingSummary Дня 9): справка —
проза-пересказ (одна «простыня», обновляется переписыванием целиком → копит дрейф,
факт нельзя проверить — «около полумиллиона»). Карточка — отдельные поля
(ключ: значение), обновляется по одному полю → дрейфа почти нет, поле либо точное,
либо его нет. Поэтому прод-2026 (Anthropic memory tool, Letta blocks, mem0) — это
структурированные поля, а не пересказы.
"""

# ──────────────────────────────────────────────────────────────────────────
# Стратегия 1 — Sliding Window
# ──────────────────────────────────────────────────────────────────────────
class SlidingWindow:
    """РОЛЬ + последние keep_last сообщений. Всё старше — отрезаем."""

    name = "окно"

    def __init__(self, keep_last=6):
        self.keep_last = keep_last        # ОКНО в сообщениях: сколько свежих слать

    def build(self, system_prompt, history):
        # Чистая нарезка списка — никакого вызова LLM. Берём хвост из keep_last
        # сообщений; всё, что раньше, в запрос НЕ попадает (модель его не увидит).
        recent = history[-self.keep_last:] if self.keep_last else list(history)
        return [{"role": "system", "content": system_prompt}, *recent]

    def view(self):
        return {"mode": self.name, "keep_last": self.keep_last}


# ──────────────────────────────────────────────────────────────────────────
# Стратегия 2 — Sticky Facts / Key-Value память
# ──────────────────────────────────────────────────────────────────────────
# Инструкция «обновлятелю» карточки. КЛЮЧЕВОЙ guardrail (урок Дня 9): на слабой
# модели «вытащи факты» при бедном сообщении провоцирует ВЫДУМЫВАНИЕ — поэтому
# строго запрещаем придумывать и велим трогать поле только при явном значении.
FACTS_GUARDRAIL = (
    "Ты ведёшь КАРТОЧКУ ФАКТОВ диалога в формате «ключ: значение» (по строке на факт). "
    "Тебе дают ТЕКУЩУЮ карточку и НОВОЕ сообщение пользователя. Верни ОБНОВЛЁННУЮ карточку. "
    "ГЛАВНОЕ ПРАВИЛО: сначала СКОПИРУЙ всю текущую карточку целиком, сохранив ВСЕ её поля "
    "дословно, и только потом добавь/измени то, что есть в новом сообщении. "
    "НИКОГДА не удаляй и не теряй уже существующее поле, если пользователь явно от него не "
    "отказался — особенно бюджет, сроки и жёсткие рамки: они критичны, держи их всегда.\n"
    "Остальные правила строго:\n"
    "1) Добавляй или меняй поле ТОЛЬКО если значение прямо присутствует в сообщении.\n"
    "2) НИЧЕГО не выдумывай: нет факта в тексте — нет поля. Не угадывай значения.\n"
    "3) Если пользователь передумал — ПЕРЕЗАПИШИ поле новым значением (одно значение на ключ).\n"
    "4) Храни важное: цель, бюджет, сроки, ограничения, предпочтения, решения, "
    "договорённости, имена, номера. Мелкие детали оформления — только если это явное решение.\n"
    "5) Формат — короткие строки «ключ: значение», без вступлений и пояснений.\n"
    "Если нового важного нет — верни ТЕКУЩУЮ карточку без изменений (но целиком)."
)


class StickyFacts:
    """РОЛЬ + карточка фактов (ключ→значение) + последние keep_last сообщений.

    extractor — функция (facts_text, user_message, guardrail) -> (text, usage),
    которую даёт агент (отдельный вызов LLM). Так модуль стратегий не знает, КАК
    зовётся модель, — он лишь решает, ЧТО положить в запрос.
    """

    name = "facts"

    def __init__(self, extractor, keep_last=6, guardrail=FACTS_GUARDRAIL):
        self.extractor = extractor        # как обновлять карточку (вызов LLM)
        self.keep_last = keep_last         # ОКНО: свежие сообщения дословно
        self.guardrail = guardrail
        self.facts = ""                    # КАРТОЧКА: строки «ключ: значение»
        self.events = []                   # лог обновлений (для «капота»)
        self.extract_usage = []            # usage вызовов-обновлений = СВОЯ цена facts
        self.seen_users = 0                # сколько реплик пользователя уже учтено (для sync)

    def update(self, user_message):
        """Обновить карточку по ОДНОЙ реплике пользователя (mem0.add() в миниатюре).

        ВАЖНО: это отдельный вызов LLM — то, чем facts платит против окна.
        Окно второго вызова не делает; facts — делает на каждую реплику.
        """
        text, usage = self.extractor(self.facts, user_message, self.guardrail)
        self.facts = (text or "").strip()
        self.events.append({"after": user_message[:40], "facts_chars": len(self.facts)})
        if usage is not None:
            self.extract_usage.append(usage)
        return self.facts

    def sync(self, history):
        """Догнать карточку по ВСЕМ ещё не учтённым репликам пользователя.

        Нужно, если в режим facts переключились ПОСРЕДИ диалога: ранее сказанные
        факты (бюджет, сроки) подхватятся из истории, а не потеряются. На обычном
        ходу обрабатывает ровно одну новую реплику (seen_users двигается по одной)."""
        users = [m for m in history if m["role"] == "user"]
        while self.seen_users < len(users):
            self.update(users[self.seen_users]["content"])
            self.seen_users += 1
        return self.facts

    def build(self, system_prompt, history):
        recent = history[-self.keep_last:] if self.keep_last else list(history)
        msgs = [{"role": "system", "content": system_prompt}]
        if self.facts:                     # карточку шлём ОТДЕЛЬНЫМ system-блоком
            msgs.append({
                "role": "system",
                "content": "Карточка фактов (важные данные из диалога):\n" + self.facts,
            })
        msgs += recent
        return msgs

    def view(self):
        return {
            "mode": self.name,
            "keep_last": self.keep_last,
            "facts": self.facts,
            "updates": len(self.events),
            "events": self.events,
        }


# ──────────────────────────────────────────────────────────────────────────
# Стратегия 3 — Branching (ветки диалога)
# ──────────────────────────────────────────────────────────────────────────
class Branching:
    """Менеджер веток. НЕ build-стратегия — другой жанр: владеет НЕСКОЛЬКИМИ
    историями сразу.

    Устройство (как git / сейв-поинты):
      trunk    — общий НЕИЗМЕНЯЕМЫЙ префикс (всё до закладки), хранится ОДИН раз;
      branches — имя ветки -> список сообщений-ДЕЛЬТЫ (только то, что ПОСЛЕ закладки);
      active   — какая ветка сейчас активна.
    Эффективная история активной ветки = trunk + её дельта (формула из брифа:
    ветка = общий_префикс ⊕ её_дельта). Дельты веток раздельны → ветки изолированы.

    Типичный поток (как в задании):
      add()×k  →  checkpoint("ТЗ собрано")  →  fork("A"), fork("B")  →
      switch("A"); add()…   switch("B"); add()…   — две независимые линии.
    """

    name = "ветки"

    def __init__(self):
        self.trunk = []                    # общий ствол (до закладки)
        self.branches = {"main": []}       # имя -> дельта
        self.active = "main"
        self.checkpoints = []              # лог закладок (для «капота»)

    def add(self, msg):
        """Дописать сообщение в АКТИВНУЮ ветку (в её дельту)."""
        self.branches[self.active].append(msg)

    def history(self):
        """Эффективная история активной ветки: общий ствол + её дельта."""
        return [*self.trunk, *self.branches[self.active]]

    def checkpoint(self, name="checkpoint"):
        """Поставить закладку: заморозить текущую историю активной ветки как
        ОБЩИЙ СТВОЛ. После этого ветки стартуют от одной точки с пустой дельтой."""
        self.trunk = list(self.history())
        self.branches = {self.active: []}  # дельты сброшены — всё ушло в ствол
        self.checkpoints.append({"name": name, "at": len(self.trunk)})
        return len(self.trunk)

    def fork(self, name):
        """Создать новую ветку ОТ ЗАКЛАДКИ: пустая дельта, общий ствол тот же.
        Это НЕ копия истории — ствол не дублируется, ветка хранит только своё."""
        self.branches.setdefault(name, [])
        return name

    def switch(self, name):
        """Переключиться на ветку. build() агента после этого соберёт trunk +
        дельту ИМЕННО этой ветки — поэтому модель видит только её линию."""
        if name in self.branches:
            self.active = name
        return self.active

    def build(self, system_prompt, history=None):
        """В ветке шлём ВСЮ эффективную историю активной ветки (про изоляцию, а
        не про экономию). history игнорируем — источник истины внутри менеджера.
        Контракт build() сохранён, чтобы агент мог звать ветки как стратегию."""
        return [{"role": "system", "content": system_prompt}, *self.history()]

    def view(self):
        return {
            "mode": self.name,
            "active": self.active,
            "trunk_len": len(self.trunk),
            "branches": {k: len(v) for k, v in self.branches.items()},
            "checkpoints": self.checkpoints,
        }
