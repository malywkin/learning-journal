"""День 3 — Разные способы рассуждения.

Берём ОДНУ аналитическую задачу и прогоняем её через 4 разных способа
«заставить модель думать»:

  1. Прямой ответ          — просто вопрос, без инструкций (базовая линия).
  2. «Решай пошагово»      — Chain-of-Thought: включаем рассуждение одной фразой.
  3. Модель пишет промпт   — meta-prompting: сначала просим модель составить
                             оптимальный промпт под задачу, потом исполняем его.
  4. Группа экспертов      — multi-persona: аналитик → инженер → критик → итог.

ВАЖНО про выбор модели (это ответ на главный вопрос дня):
  Мы НАМЕРЕННО берём ОБЫЧНУЮ instruct-модель (gemma), а НЕ reasoning-модель.
  Reasoning-модель (o-серия, R1, nemotron) «думает про себя» ВСЕГДА — поэтому
  на ней способ 1 и способ 2 слились бы в почти одинаковый ответ, и сравнение
  было бы нечестным. Instruct-модель по умолчанию НЕ рассуждает — значит разница
  между «прямым» и «пошагово» будет реально видна. Это контроль переменной:
  единственное, что меняется между прогонами, — ФОРМА промпта.

  Запусти с флагом `--reasoning`, чтобы прогнать те же 4 способа на reasoning-
  модели и УВИДЕТЬ своими глазами, как способы 1 и 2 там схлопываются.
"""

import os
import sys

from dotenv import load_dotenv
from openai import OpenAI

# --- Клиент (OpenRouter совместим с OpenAI SDK: отличаются base_url и ключ) ---
load_dotenv()
client = OpenAI(
    api_key=os.environ["OPENROUTER_API_KEY"],
    base_url="https://openrouter.ai/api/v1",
)

# Обычная instruct-модель: НЕ reasoning, отвечает «с ходу» — то, что нам нужно.
MODEL_INSTRUCT = "google/gemma-4-31b-it:free"
# Reasoning-модель для опционального демо (--reasoning): «думает» всегда сама.
MODEL_REASONING = "nvidia/nemotron-3-super-120b-a12b:free"

# Держим температуру одинаковой во всех способах — чтобы сравнение было честным
# (меняем только промпт, а не «разброс» модели).
TEMPERATURE = 0.3

# --- Одна задача на все 4 способа. Юридический вопрос С ПРОБЕЛОМ В ПРАВЕ:
#     прямого ответа в законе нет, нужно толкование/аналогия — значит способы
#     РАЗОЙДУТСЯ (в отличие от арифметики, где ответ один). ---
TASK = (
    "По российскому праву. После смерти человека остались цифровые активы: "
    "криптовалюта на кошельке (доступ только по приватному ключу), аккаунт в "
    "соцсети с монетизацией и предметы в онлайн-игре. Входят ли эти активы в "
    "состав наследства и как наследники могут получить к ним доступ? "
    "Дай юридически обоснованный ответ."
)


def call(model, messages):
    """Один запрос к модели. Возвращает (текст_ответа, потрачено_токенов)."""
    resp = client.chat.completions.create(
        model=model,
        messages=messages,
        temperature=TEMPERATURE,
    )
    return resp.choices[0].message.content, resp.usage.completion_tokens


# ---------------------------------------------------------------------------
# СПОСОБ 1. Прямой ответ — никаких инструкций, только вопрос.
# Базовая линия: как модель решает «не думая».
# ---------------------------------------------------------------------------
def method_direct(model):
    return call(model, [{"role": "user", "content": TASK}])


# ---------------------------------------------------------------------------
# СПОСОБ 2. «Решай пошагово» — Chain-of-Thought.
# Одна фраза заставляет модель СНАЧАЛА развернуть рассуждение. Поскольку текст
# генерируется слева направо, к моменту вывода итога у модели уже есть опора
# из промежуточных шагов — и ответ обычно точнее.
# ---------------------------------------------------------------------------
def method_cot(model):
    return call(
        model,
        [
            {
                "role": "system",
                "content": "Решай задачу пошагово: сначала рассуждай по шагам, "
                "только потом дай итоговую рекомендацию.",
            },
            {"role": "user", "content": TASK},
        ],
    )


# ---------------------------------------------------------------------------
# СПОСОБ 3. Модель сама пишет промпт — meta-prompting.
# Два запроса: (1) просим модель составить ОПТИМАЛЬНЫЙ промпт под задачу;
# (2) подставляем этот сгенерированный промпт и получаем ответ по нему.
# Идея: модель «знает», как лучше себя спросить — пусть сформулирует ТЗ сама.
# ---------------------------------------------------------------------------
def method_self_prompt(model):
    # Шаг 1: модель сочиняет промпт (сам ответ на задачу пока НЕ даём).
    generated_prompt, _ = call(
        model,
        [
            {
                "role": "user",
                "content": "Составь максимально эффективный промпт для решения "
                "следующей задачи. Выведи ТОЛЬКО текст промпта, без решения.\n\n"
                f"Задача: {TASK}",
            }
        ],
    )
    # Шаг 2: исполняем сгенерированный промпт.
    answer, tokens = call(model, [{"role": "user", "content": generated_prompt}])
    return answer, tokens, generated_prompt


# ---------------------------------------------------------------------------
# СПОСОБ 4. Группа экспертов — multi-persona. ДОКТРИНАЛЬНЫЙ состав под право.
# Один запрос, но system-промпт разворачивает разбор из трёх ролей подряд.
# Тонкость (и связь с механикой токенов): текст идёт слева направо, поэтому
# Критик, идущий ПОСЛЕ Теоретика и Практика, видит их доводы и может их оспорить
# — он ловит слабые места в аргументации. Это и есть смысл «панели».
# ---------------------------------------------------------------------------
def method_experts(model):
    return call(
        model,
        [
            {
                "role": "system",
                "content": (
                    "Ты ведёшь юридический разбор тремя экспертами. Ответь строго "
                    "по ролям, по очереди:\n"
                    "1) ТЕОРЕТИК — реши через доктрину: аналогия закона, аналогия "
                    "права, общие принципы; укажи, какими нормами закрывается "
                    "пробел.\n"
                    "2) ПРАКТИК — как реально решит суд: судебная практика, позиции "
                    "Верховного суда, сложившиеся подходы.\n"
                    "3) КРИТИК — оспорь доводы первых двух: слабые места, риски, "
                    "контраргументы, что упущено.\n"
                    "В конце — ИТОГ: взвешенная позиция с учётом всех троих."
                ),
            },
            {"role": "user", "content": TASK},
        ],
    )


def section(title, body, tokens, extra=None):
    """Печатает один способ блоком, чтобы ответы было удобно сравнивать."""
    print(f"\n{'=' * 70}\n{title}\n{'=' * 70}")
    if extra:
        print(f"[Сгенерированный моделью промпт]\n{extra}\n{'-' * 70}")
    print(body)
    print(f"\n[completion_tokens = {tokens}]")


if __name__ == "__main__":
    # По умолчанию — instruct-модель (чистое сравнение). С флагом --reasoning
    # прогоняем то же на reasoning-модели, чтобы увидеть слияние способов 1 и 2.
    use_reasoning = "--reasoning" in sys.argv
    model = MODEL_REASONING if use_reasoning else MODEL_INSTRUCT

    print(f"Модель: {model}")
    print(f"Задача: {TASK}")

    d_ans, d_tok = method_direct(model)
    section("СПОСОБ 1 — ПРЯМОЙ ОТВЕТ", d_ans, d_tok)

    c_ans, c_tok = method_cot(model)
    section("СПОСОБ 2 — ПОШАГОВО (Chain-of-Thought)", c_ans, c_tok)

    s_ans, s_tok, s_prompt = method_self_prompt(model)
    section("СПОСОБ 3 — МОДЕЛЬ САМА СОСТАВИЛА ПРОМПТ", s_ans, s_tok, extra=s_prompt)

    e_ans, e_tok = method_experts(model)
    section("СПОСОБ 4 — ГРУППА ЭКСПЕРТОВ", e_ans, e_tok)

    # Подсказка для сравнения (это и есть «Результат» задания — выводы пишешь сам).
    print(f"\n{'#' * 70}")
    print("СРАВНИ САМ: на вопросе с пробелом в праве прямой ответ обычно беднее —")
    print("даёт одну позицию без аналогии и контрдоводов; способы 2–4 разворачивают")
    print("толкование. 'Самый точный' = самый полный и юридически обоснованный разбор.")
