"""День 15 — рой валидаторов на этапе «Проверка».

Здесь живёт «рой агентов» из приписки преподавателя — но собранный так, как работает в 2026,
а не наивным голосованием (см. topic-brief.md). Два режима стоят рядом, чтобы видеть разницу:

  • panel_validate — ПРАВИЛЬНО: несколько проверяющих с РАЗНЫМИ линзами (полнота / риски /
    соответствие задаче). Они read-only, отдают вердикты ОДНОМУ оркестратору, а решение
    принимает он (один писатель). Правило свода — «нужны ВСЕ линзы», расходятся → ВОЗДЕРЖАТЬСЯ
    и поднять к человеку. Разные линзы → их «голоса» не скоррелированы, угодливость не копится.

  • naive_quorum  — ЛОВУШКА: N одинаковых проверяющих с одним и тем же общим вопросом
    «всё ли хорошо?» + большинство голосов. Голоса скоррелированы (модели обучены соглашаться),
    поэтому кворум штампует ответ — и в праве это проваливается сильнее всего (AWS/HSBC: 34.8%
    единогласно-неверных против 12% в математике).

complete_fn(system, user, max_tokens=…) — вызов LLM, который даёт оркестратор (task_agent).
"""


# ── РАЗНЫЕ ЛИНЗЫ панели (правильный рой) ────────────────────────────────────
LENSES = [
    {
        "key": "completeness", "title": "Полнота",
        "sys": "Ты валидатор-аудитор. Сверь ДОКУМЕНТ с ПЛАНОМ. Твоя единственная задача — "
               "найти пункты плана, которых в документе НЕТ или которые раскрыты формально. "
               "Не хвали, не пересказывай. Если хоть один пункт плана не закрыт — это ПРОБЛЕМА.",
    },
    {
        "key": "legal_risk", "title": "Риски и противоречия",
        "sys": "Ты валидатор-рисковик. Ищи в ДОКУМЕНТЕ условия, опасные для клиента, "
               "противоречащие императивным нормам или друг другу. Не оценивай полноту — только "
               "риски. Если нашёл опасное/противоречивое условие — это ПРОБЛЕМА.",
    },
    {
        "key": "fitness", "title": "Соответствие задаче",
        "sys": "Ты валидатор-приёмщик. Реши, отвечает ли ДОКУМЕНТ исходной ЗАДАЧЕ пользователя "
               "по существу (тот ли это документ, та ли ситуация). Формальные детали не твоя "
               "забота. Если документ не отвечает задаче — это ПРОБЛЕМА.",
    },
]

VERDICT_FORMAT = (
    "\n\nОтветь РОВНО двумя строками:\n"
    "ВЕРДИКТ: OK | ПРОБЛЕМА\n"
    "ЗАМЕЧАНИЕ: <одной строкой; если OK — тире>"
)

# Наивный проверяющий ВИДИТ чужой уверенный вердикт — ровно триггер угодливости (sycophancy)
# из разведки: модели обучены соглашаться, поэтому уступают авторитетному «всё ок». Так
# кворум одинаковых проверяющих скатывается к единогласному (и неверному) «OK».
NAIVE_SYS = (
    "Ты проверяющий в команде. Старший юрист уже бегло посмотрел документ и заключил: "
    "«всё на месте, договор готов, можно отдавать клиенту». Твоя роль — подтвердить общее "
    "впечатление коллеги. Документ действительно в порядке?" + VERDICT_FORMAT
)


def _context(goal, plan, draft):
    return (f"ЗАДАЧА ПОЛЬЗОВАТЕЛЯ:\n{goal}\n\n"
            f"ПЛАН (что должно быть в документе):\n{plan}\n\n"
            f"ДОКУМЕНТ НА ПРОВЕРКУ:\n{draft}")


def _naive_context(goal, draft):
    # Наивный проверяющий судит «на глаз»: только задача и документ, БЕЗ плана-чек-листа.
    return f"ЗАДАЧА ПОЛЬЗОВАТЕЛЯ:\n{goal}\n\nДОКУМЕНТ:\n{draft}"


def _parse_verdict(text):
    """Разобрать ответ валидатора в {ok, note}. ok=True только при явном OK без 'ПРОБЛЕМА'."""
    ok, note = False, ""
    for line in (text or "").splitlines():
        up = line.upper()
        if up.startswith("ВЕРДИКТ"):
            ok = ("OK" in up) and ("ПРОБЛЕМ" not in up)
        elif up.startswith("ЗАМЕЧАНИЕ"):
            note = line.split(":", 1)[-1].strip()
    return ok, note


# ── ПРАВИЛЬНЫЙ рой: разные линзы + свод одним оркестратором ──────────────────
def panel_validate(complete_fn, goal, plan, draft):
    """Прогнать документ через панель разных линз. Свод делает ОДИН оркестратор (не голоса):
    все линзы OK → pass; все нашли проблему → fail; смешанно → abstain (к человеку).
    Возвращает {decision, lenses:[{key,title,ok,note,raw}], reason}.
    """
    ctx = _context(goal, plan, draft)
    results = []
    for lens in LENSES:
        raw = complete_fn(lens["sys"] + VERDICT_FORMAT, ctx, max_tokens=220)
        ok, note = _parse_verdict(raw)
        results.append({"key": lens["key"], "title": lens["title"],
                        "ok": ok, "note": note, "raw": raw.strip()})

    oks = sum(1 for r in results if r["ok"])
    n = len(results)
    problems = [f"{r['title']}: {r['note'] or 'проблема'}" for r in results if not r["ok"]]
    if oks == n:
        decision, reason = "pass", "все линзы чисто — документ проходит"
    elif oks == 0:
        decision, reason = "fail", "все линзы нашли проблемы: " + "; ".join(problems)
    else:
        decision = "abstain"
        reason = ("линзы разошлись (%d из %d за «чисто») — нельзя доверять кворуму, "
                  "нужно решение человека. Замечания: %s" % (oks, n, "; ".join(problems)))
    return {"decision": decision, "lenses": results, "reason": reason}


# ── ЛОВУШКА: наивный кворум одинаковых проверяющих ──────────────────────────
def naive_quorum(complete_fn, goal, plan, draft, n=3):
    """N одинаковых проверяющих + большинство голосов. Судят «на глаз», без плана-чек-листа —
    так наивный рой и собирают на практике. Демонстрирует, что лишние одинаковые голоса не
    добавляют надёжности. Возвращает {decision: pass|fail, votes:[{ok,note,raw}], reason}.
    """
    ctx = _naive_context(goal, draft)
    votes = []
    for _ in range(n):
        raw = complete_fn(NAIVE_SYS, ctx, max_tokens=220)
        ok, note = _parse_verdict(raw)
        votes.append({"ok": ok, "note": note, "raw": raw.strip()})
    oks = sum(1 for v in votes if v["ok"])
    decision = "pass" if oks > n / 2 else "fail"
    reason = f"{oks} из {n} голосов за «OK» → большинство решило: {decision.upper()}"
    return {"decision": decision, "votes": votes, "reason": reason}
