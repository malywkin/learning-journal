"""День 15 — демонстрации (живые вызовы OpenRouter).

run_trap   — ЛОВУШКА: один и тот же документ с НАМЕРЕННЫМ пробелом гоним через наивный
             кворим одинаковых проверяющих и через панель разных линз. Цель — увидеть, как
             наивный кворум штампует «OK», а панель ловит пробел.
run_cycle  — полный цикл задачи в режиме «само» (ask_between=False): planning → execution →
             validation → done, с печатью ворот на каждом переходе.

Запуск: .venv/bin/python demos.py trap   |   .venv/bin/python demos.py cycle
"""
import sys

from dotenv import load_dotenv

from swarm import naive_quorum, panel_validate
from task_agent import TaskAgent
from task_state import TITLE, TaskState

load_dotenv()


# Документ с НАМЕРЕННЫМ пробелом: в плане есть СРОК аренды и ЗАЛОГ, а в договоре их НЕТ.
GOAL = "составить договор аренды квартиры между физлицами"
PLAN = (
    "1. Стороны (наймодатель и наниматель).\n"
    "2. Предмет — квартира, адрес, состояние.\n"
    "3. Размер арендной платы и порядок оплаты.\n"
    "4. СРОК найма (на какой период заключается договор).\n"
    "5. Обеспечительный платёж (залог): размер и порядок возврата.\n"
    "6. Порядок расторжения."
)
DRAFT_WITH_GAP = (
    "ДОГОВОР НАЙМА ЖИЛОГО ПОМЕЩЕНИЯ\n\n"
    "г. Москва\n\n"
    "1. ОБЩИЕ ПОЛОЖЕНИЯ. Гражданин(ка) ______ (далее — Наймодатель), с одной стороны, и "
    "гражданин(ка) ______ (далее — Наниматель), с другой стороны, заключили настоящий договор "
    "о нижеследующем.\n\n"
    "2. ПРЕДМЕТ ДОГОВОРА. Наймодатель передаёт Нанимателю за плату во владение и пользование "
    "жилое помещение — квартиру по адресу: ______, общей площадью ___ кв. м. Квартира "
    "передаётся в состоянии, пригодном для проживания, что подтверждается актом приёма-передачи.\n\n"
    "3. ПРАВА И ОБЯЗАННОСТИ СТОРОН. Наниматель обязуется использовать помещение по назначению, "
    "поддерживать его в исправном состоянии и своевременно вносить плату. Наймодатель обязуется "
    "не препятствовать проживанию и проводить капитальный ремонт за свой счёт.\n\n"
    "4. АРЕНДНАЯ ПЛАТА. Размер платы составляет 40 000 (сорок тысяч) рублей в месяц. Оплата "
    "производится ежемесячно не позднее 5-го числа путём перевода на счёт Наймодателя.\n\n"
    "5. ОТВЕТСТВЕННОСТЬ СТОРОН. За нарушение обязательств стороны несут ответственность в "
    "соответствии с действующим законодательством Российской Федерации.\n\n"
    "6. РАСТОРЖЕНИЕ. Договор может быть расторгнут по соглашению сторон, а также по инициативе "
    "любой из сторон с письменным уведомлением за 30 дней.\n\n"
    "7. ЗАКЛЮЧИТЕЛЬНЫЕ ПОЛОЖЕНИЯ. Договор составлен в двух экземплярах, имеющих равную силу. "
    "Подписи сторон: __________ / __________."
    # Выглядит как готовый договор, НО тихо отсутствуют: пункт 4 плана (СРОК найма) и
    # пункт 5 плана (обеспечительный платёж/залог). Это и есть пробел для ловушки.
)


def run_trap():
    agent = TaskAgent()
    print("=== ЛОВУШКА: один документ с пробелом (нет срока и залога) ===\n")

    print("--- Наивный кворум (3 одинаковых проверяющих, общий вопрос «всё ли хорошо?») ---")
    nq = naive_quorum(agent.complete, GOAL, PLAN, DRAFT_WITH_GAP, n=3)
    for i, v in enumerate(nq["votes"], 1):
        print(f"  голос {i}: {'OK' if v['ok'] else 'ПРОБЛЕМА'} — {v['note'] or '—'}")
    print("  РЕШЕНИЕ кворума:", nq["decision"].upper(), "|", nq["reason"], "\n")

    print("--- Панель разных линз (полнота / риски / соответствие) ---")
    pv = panel_validate(agent.complete, GOAL, PLAN, DRAFT_WITH_GAP)
    for r in pv["lenses"]:
        print(f"  [{r['title']}] {'OK' if r['ok'] else 'ПРОБЛЕМА'} — {r['note'] or '—'}")
    print("  РЕШЕНИЕ панели:", pv["decision"].upper(), "|", pv["reason"], "\n")

    print("ИТОГ: кворум =", nq["decision"].upper(), "| панель =", pv["decision"].upper())
    print(
        "\nЧестно о том, что видно:\n"
        "• Наивный кворум — это 3× почти одинаковых расплывчатых мнения (часто с шумом:\n"
        "  придирки к пустым полям как к «пропускам»). Лишние ОДИНАКОВЫЕ голоса надёжности\n"
        "  не добавляют — это тот же ответ трижды.\n"
        "• Панель разных линз даёт ТОЧНЫЕ, привязанные к плану находки и, главное, умеет\n"
        "  ВОЗДЕРЖАТЬСЯ, когда линзы расходятся → эскалация к человеку (фикс 2026 против\n"
        "  ложной уверенности кворума).\n"
        "• Документированную угодливость (кворим штампует НЕВЕРНЫЙ ответ) мы пытались\n"
        "  спровоцировать (сказали проверяющим «старший юрист уже одобрил») — эта модель\n"
        "  устояла. Эффект из исследования (право 34.8% единогласно-неверных) — это масштаб\n"
        "  и много раундов спора; на нашей маленькой модели он не воспроизводится. Это сам\n"
        "  по себе урок: проверяй поведение живьём, не верь громкому числу на слово.")


def run_cycle():
    agent = TaskAgent(max_revisions=1)
    st = TaskState(GOAL, path=None, ask_between=False)     # режим «само»
    print("=== ПОЛНЫЙ ЦИКЛ (ask_between=False): planning → execution → validation → done ===\n")
    agent.run_current(st)                                  # planning + авто-одобрение плана
    agent.run_all(st)                                      # гоним по воротам до финала
    for t in st.transitions:
        print(f"  переход: {TITLE[t['from']]} → {TITLE[t['to']]}  ({t['reason']})")
    print("\n  итоговый этап:", st.stage, f"({TITLE[st.stage]})")
    print("  вердикт панели:", st.validation.get("decision"))
    print("  токенов всего:", agent.ledger[-1]["cumulative"] if agent.ledger else 0)


if __name__ == "__main__":
    which = sys.argv[1] if len(sys.argv) > 1 else "trap"
    (run_trap if which == "trap" else run_cycle)()
