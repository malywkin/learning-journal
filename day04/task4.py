"""День 4 — Температура (temperature).

Берём ОДИН и тот же запрос и прогоняем его при трёх температурах из задания:
0.0, 0.7, 1.2 — и сравниваем ответы по точности / креативности / разнообразию.

ЧТО ТАКОЕ ТЕМПЕРАТУРА (под капотом)
-----------------------------------
Модель на каждом шаге не «знает» следующее слово — она считает ВЕРОЯТНОСТЬ для
каждого возможного токена (кусочка слова). Получается распределение: у одних
токенов вероятность высокая, у других низкая. Температура — это «ручка», которая
МАСШТАБИРУЕТ это распределение ПЕРЕД выбором (через softmax с делением логитов
на T):

  • T → 0   : распределение становится «острым» — почти вся вероятность у самого
             верного токена. Модель каждый раз берёт самый ожидаемый вариант →
             ответ предсказуемый, точный, скучный, почти не меняется от прогона
             к прогону.
  • T ≈ 0.7 : распределение умеренно «размывается» — у модели появляется выбор
             между несколькими хорошими вариантами. Баланс точности и свежести.
  • T = 1.2 : распределение «плоское» — даже маловероятные токены получают шанс.
             Ответ креативный и разный каждый раз, но рискует «поплыть»
             (бессвязность, выдумки).

ВАЖНЫЙ НЮАНС (сверено с источниками, 2026):
  temperature=0 НЕ гарантирует одинаковый ответ. На точную математику накладываются
  ошибки округления (float), параллельные вычисления на GPU и то, что облачный API
  раскидывает запросы по разным серверам. Поэтому даже при T=0 ответы могут чуть
  отличаться — «детерминированно» здесь значит «максимально стабильно», а не «бит в бит».

  Температура — не единственная ручка случайности. Рядом есть top_p (nucleus): он
  оставляет только самые вероятные токены, набирающие в сумме долю p, и сэмплирует
  из них. Обычно крутят ЧТО-ТО ОДНО. Мы трогаем только temperature, top_p держим
  по умолчанию (=1.0), чтобы переменная была одна.

ПОЧЕМУ ТВОРЧЕСКАЯ ЗАДАЧА:
  На фактическом вопросе («столица Франции») при любой температуре будет «Париж» —
  сравнивать нечего. Разница температур видна там, где у задачи МНОГО хороших
  ответов — то есть на творческой. Поэтому основная задача ниже — придумать слоган.
  (В app.py есть пресет-контраст с фактическим вопросом — на нём видно, что там
  температура почти не влияет. Это и есть ответ на вопрос «для каких задач что».)

ПОЧЕМУ INSTRUCT-МОДЕЛЬ:
  Берём обычную instruct-модель (gemma): она честно реагирует на temperature.
  Reasoning-модели часто игнорируют/переопределяют этот параметр — сравнение было
  бы нечестным.
"""

import os
import time

from dotenv import load_dotenv
from openai import OpenAI, RateLimitError

# --- Клиент (OpenRouter совместим с OpenAI SDK: отличаются base_url и ключ) ---
load_dotenv()
client = OpenAI(
    api_key=os.environ["OPENROUTER_API_KEY"],
    base_url="https://openrouter.ai/api/v1",
)

# Обычная instruct-модель: честно уважает temperature.
MODEL = "google/gemma-4-31b-it:free"

# Три температуры ровно из задания.
TEMPS = [0.0, 0.7, 1.2]

# Сколько раз повторить ОДИН и тот же запрос на КАЖДОЙ температуре.
# Это и показывает «разнообразие»: при T=0 повторы почти одинаковы, при T=1.2 — разные.
N_RUNS = 3

# --- Творческая задача: много хороших ответов => разброс температур виден. ---
TASK = (
    "Придумай оригинальный слоган для маленькой городской кофейни. "
    "Дай ОДИН слоган, до 10 слов, без пояснений."
)


def call(prompt, temperature, retries=4, pause=15):
    """Один запрос к модели при заданной температуре. Возвращает текст ответа.

    Бесплатные модели OpenRouter ограничены по числу запросов в минуту: при
    превышении прилетает 429. Ловим его и повторяем после паузы (простой backoff) —
    это стандартная практика устойчивости к rate-limit.
    """
    for attempt in range(retries):
        try:
            resp = client.chat.completions.create(
                model=MODEL,
                messages=[{"role": "user", "content": prompt}],
                temperature=temperature,
                # top_p НЕ трогаем (=1.0) — меняем только одну ручку, температуру.
            )
            return resp.choices[0].message.content.strip()
        except RateLimitError:
            if attempt == retries - 1:
                raise
            time.sleep(pause)  # подождать сброса поминутного лимита и повторить


def run_temperature(prompt, temperature, n_runs=N_RUNS):
    """Прогоняет один и тот же промпт n_runs раз при одной температуре."""
    return [call(prompt, temperature) for _ in range(n_runs)]


def unique_count(answers):
    """Грубая метрика разнообразия: сколько РАЗНЫХ ответов среди повторов.

    Нормализуем (регистр/пробелы), кладём в множество. 1 из N => модель повторяет
    одно и то же (низкое разнообразие); N из N => каждый раз новый (высокое).
    """
    norm = {" ".join(a.lower().split()) for a in answers}
    return len(norm)


if __name__ == "__main__":
    print(f"Модель: {MODEL}")
    print(f"Задача: {TASK}")
    print(f"Повторов на температуру: {N_RUNS}\n")

    for t in TEMPS:
        answers = run_temperature(TASK, t)
        uniq = unique_count(answers)
        print("=" * 70)
        print(f"TEMPERATURE = {t}   (разных ответов: {uniq} из {N_RUNS})")
        print("=" * 70)
        for i, a in enumerate(answers, 1):
            print(f"  [{i}] {a}")
        print()

    print("#" * 70)
    print("КАК ЧИТАТЬ:")
    print("• T=0   — ответы почти совпадают (разных ~1): точно, стабильно, но скучно.")
    print("• T=0.7 — варианты разные, но связные: баланс — рабочая середина.")
    print("• T=1.2 — все разные, ярче и неожиданнее, но рискуют 'поплыть'.")
    print("Вывод: точность/факты/код -> низкая T; брейншторм/тексты -> высокая T.")
